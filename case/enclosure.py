# --- KiCad placement ------------------------------------------------------------
def footprint_positions(pcb_file, rotations=None):
    """Return {reference: (x, y)} in STEP coordinates (Y flipped). If a dict is
    passed as rotations it is filled with {reference: angle}."""
    text = pcb_file.read_text(encoding="utf8")
    pos = {}
    for m in re.finditer(r'\(footprint "[^"]+"\s.*?\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)', text, re.S):
        ref = re.search(r'\(property "Reference" "([^"]+)"', text[m.start():m.start() + 3000])
        if ref:
            pos[ref.group(1)] = (float(m.group(1)), -float(m.group(2)))
            if rotations is not None:
                rotations[ref.group(1)] = float(m.group(3) or 0)
    return pos


def generated_model(module_name, var, loc=None):
    """Build a coloured Compound from a make_*.py part list (footprint frame;
    the generator uses +y down, flipped here as the STEP writer does). loc, a
    Location, is applied to every part: moving a Compound afterwards would
    leave its children where they were."""
    if str(MODELS_DIR) not in sys.path:
        sys.path.insert(0, str(MODELS_DIR))
    model = getattr(importlib.import_module(module_name), var)
    kids = []
    for part in model.parts:
        kind, name, cname = part[:3]
        if kind == "box":
            x0, y0, z0, x1, y1, z1 = part[3:]
            shp = box(x0, -y1, z0, x1, -y0, z1)
        elif kind == "cyl":
            cx, cy, r, z0, z1 = part[3:]
            shp = Pos(cx, -cy, z0) * Cylinder(r, z1 - z0, align=(Align.CENTER, Align.CENTER, Align.MIN))
        else:  # xcyl, axis along +x
            cy, cz, r, x0, x1 = part[3:]
            shp = Pos(x0, -cy, cz) * Rot(0, 90, 0) * Cylinder(r, x1 - x0,
                                                              align=(Align.CENTER, Align.CENTER, Align.MIN))
        if loc is not None:
            shp = loc * shp
        shp.label = name
        shp.color = Color(*model.colors[cname])
        kids.append(shp)
    return Compound(children=kids, label=model.name)


def colorize_pcb(pcb):
    """Replace the flattened custom models in the exported assembly with
    coloured rebuilds, and hang an antenna on every radio module. Each rebuild
    is rotated by its footprint angle and shifted so its bounding box lands on
    the exported child's; the antenna gets the same transform as its module."""
    rot = {}
    footprint_positions(KICAD_PCB, rot)
    kids = []
    for child in pcb.children:
        gen = GENERATED_MODELS.get(child.label)
        if not gen:
            kids.append(child)
            continue
        module, var, ref = gen
        angle = rot.get(ref, 0.0)
        rotated = Rot(0, 0, angle) * generated_model(module, var)
        d = child.bounding_box().min - rotated.bounding_box().min
        loc = Pos(d.X, d.Y, d.Z) * Rot(0, 0, angle)
        model = generated_model(module, var, loc)
        model.label = child.label
        kids.append(model)
        if child.label == "nRF24L01_PA_LNA":
            ant = generated_model(*ANTENNA_MODEL, loc)
            ant.label = "antenna"
            kids.append(ant)
    out = Compound(children=kids)
    out.label = pcb.label
    return out


def parts_of(child):
    """The shapes to test for a top-level child of the PCB assembly: the
    individual parts of a rebuilt model (each already placed), or the child
    itself for an imported KiCad library model, whose placement sits on this
    node and not on the solid below it."""
    if child.label in GENERATED_MODELS or child.label == "antenna":
        return list(child.children)
    return [child]


def ui_xy(fp, u, v):
    """UI module drawing coords (u right, v down from top-left) -> STEP XY."""
    return fp[0] + (u - 11.38), fp[1] - (v - 1.93)


def load_pcb():
    """Export the KiCad assembly to STEP if missing or stale, then import it."""
    if not PCB_STEP.exists() or PCB_STEP.stat().st_mtime < KICAD_PCB.stat().st_mtime:
        PCB_STEP.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            [str(KICAD_CLI), "pcb", "export", "step", "--subst-models", "--force",
             "-o", str(PCB_STEP), str(KICAD_PCB)],
            check=True,
        )
    return colorize_pcb(import_step(str(PCB_STEP)))


# --- Helpers ----------------------------------------------------------------------
def box(x0, y0, z0, x1, y1, z1):
    return Pos(x0, y0, z0) * Box(x1 - x0, y1 - y0, z1 - z0, align=Align.MIN)


def rounded_prism(x0, y0, x1, y1, z0, z1, r):
    p = box(x0, y0, z0, x1, y1, z1)
    return fillet(p.edges().filter_by(Axis.Z), r) if r > 0 else p


def tile(a, b, w, gap):
    """Spans of width w with gap between them, centred in [a, b]. A span that
    does not fit at all yields nothing; a single too-long span is shortened."""
    n = int((b - a + gap) // (w + gap))
    if n == 0:
        return [(a, b)] if b - a >= w / 2 else []
    total = n * w + (n - 1) * gap
    start = a + (b - a - total) / 2
    return [(start + i * (w + gap), start + i * (w + gap) + w) for i in range(n)]


def vent_slots(x0, y0, z0, x1, y1, z1, along):
    """Cutters for a field of slots filling the box, slots running along 'x'
    or 'y' with ribs between them and along their length."""
    cutters = []
    if along == "x":
        rows, segs = tile(y0, y1, VENT_W, VENT_RIB), tile(x0, x1, VENT_SEG, VENT_RIB)
        for ya, yb in rows:
            for xa, xb in segs:
                cutters.append(box(xa, ya, z0, xb, yb, z1))
    else:
        cols, segs = tile(x0, x1, VENT_W, VENT_RIB), tile(y0, y1, VENT_SEG, VENT_RIB)
        for xa, xb in cols:
            for ya, yb in segs:
                cutters.append(box(xa, ya, z0, xb, yb, z1))
    return cutters


def shelf(x0, x1, y_wall, y_root, y_in, z_top, z_bot):
    """Block growing inwards (+Y) from the front wall, from y_root (inside the
    wall) to y_in, with a 45 degree underside back to the wall face at y_wall
    so it prints without support."""
    drop = y_in - y_wall
    pts = [(y_root, z_top), (y_in, z_top), (y_in, z_bot),
           (y_wall, z_bot - drop), (y_root, z_bot - drop)]
    profile = Plane(origin=(x0, 0, 0), x_dir=(0, 1, 0), z_dir=(1, 0, 0)) * Polygon(*pts, align=None)
    return extrude(profile, amount=x1 - x0, dir=(1, 0, 0))


def build():
    fp = footprint_positions(KICAD_PCB)
    radios = [fp[r] for r in ("M1", "M2", "M3", "M4")]
    holes = [fp[r] for r in ("MH1", "MH2", "MH3", "MH4")]
    ui = fp["J1"]
    esp = fp["U1"]

    # Inner cavity footprint.
    ix0, ix1 = 0.0 - CLEARANCE, 96.5 + CLEARANCE
    iy0 = -73.2 - CLEARANCE
    back_outer = radios[0][1] + SMA_BODY_FROM_PIN1 - SMA_WALL_GAP
    iy1 = back_outer - WALL
    ox0, ox1, oy0, oy1 = ix0 - WALL, ix1 + WALL, iy0 - WALL, back_outer

    floor_bot = -STANDOFF_H - FLOOR
    floor_top = -STANDOFF_H

    # ---- Base -------------------------------------------------------------------
    base = rounded_prism(ox0, oy0, ox1, oy1, floor_bot, SPLIT_Z, CORNER_R)
    base -= box(ix0, iy0, floor_top, ix1, iy1, SPLIT_Z + 1)
    lip_outer = rounded_prism(ix0 - LIP_T, iy0 - LIP_T, ix1 + LIP_T, iy1 + LIP_T,
                              SPLIT_Z, SPLIT_Z + LIP_H, max(CORNER_R - WALL + LIP_T, 0.5))
    base += lip_outer - box(ix0, iy0, SPLIT_Z - 1, ix1, iy1, SPLIT_Z + LIP_H + 1)
    for x, y in holes:
        base += Pos(x, y, floor_top) * Cylinder(STANDOFF_D / 2, STANDOFF_H,
                                                 align=(Align.CENTER, Align.CENTER, Align.MIN))
        base -= Pos(x, y, -INSERT_DEPTH) * Cylinder(INSERT_D / 2, INSERT_DEPTH + 0.1,
                                                     align=(Align.CENTER, Align.CENTER, Align.MIN))

    # ---- Lid --------------------------------------------------------------------
    bay_x0 = esp[0] + ESP_PCB_X[0] - USB_BAY_SIDE   # USB bay opening, X
    bay_x1 = esp[0] + ESP_PCB_X[1] + USB_BAY_SIDE
    plat_x0 = bay_x0 - USB_BAY_SIDE_W      # strip inner wall = bay left wall
    plat_y1 = esp[1] + 1.5 + 1.0           # ESP32 PCB top end plus margin
    tall = rounded_prism(ox0, oy0, ox1, oy1, SPLIT_Z, PLAT_TOP + 1, CORNER_R)
    outer = tall & (box(ox0, oy0, SPLIT_Z, ox1, oy1, DECK_TOP)
                    + box(plat_x0 - WALL, oy0, SPLIT_Z, ox1, plat_y1 + WALL, PLAT_TOP))
    cavity = (box(ix0, iy0, SPLIT_Z - 1, ix1, iy1, DECK_UNDER)
              + box(plat_x0, iy0, SPLIT_Z - 1, ix1, plat_y1, PLAT_UNDER))
    lid = outer - cavity
    # Snap latches: tab plate on the lid's outer wall running LATCH_L below the
    # split, hook with a 45 degree lead-in at its bottom, pocket in the base.
    z_bot = SPLIT_Z - LATCH_L
    z_ramp = z_bot + LATCH_GAP + LATCH_HOOK_D
    z_top = z_ramp + LATCH_HOOK_H
    for xw, d in ((ox0, +1), (ox1, -1)):            # wall outer face, inward direction
        for yf in LATCH_Y_FROM_FRONT:
            yc = iy0 + yf
            y0, y1 = yc - LATCH_W / 2, yc + LATCH_W / 2
            xt_in = xw - d * LATCH_GAP               # tab inner face
            xt_out = xt_in - d * LATCH_T
            xi = xt_in + d * (LATCH_GAP + LATCH_HOOK_D)   # hook tip
            lid += box(min(xt_in, xt_out), y0, z_bot, max(xt_in, xt_out), y1, DECK_TOP)
            hook = [(xt_in, z_bot), (xi, z_ramp), (xi, z_top), (xt_in, z_top)]
            prof = Plane(origin=(0, y0, 0), x_dir=(1, 0, 0), z_dir=(0, -1, 0)) * Polygon(*hook, align=None)
            lid += extrude(prof, amount=LATCH_W, dir=(0, 1, 0))
            lid += box(min(xt_out, xt_out - d * LATCH_NAIL), y0, z_bot,
                       max(xt_out, xt_out - d * LATCH_NAIL), y1, z_bot + 1.2)
            base -= box(min(xw - d, xi + d * LATCH_FIT), y0 - LATCH_FIT, z_bot - LATCH_FIT,
                        max(xw - d, xi + d * LATCH_FIT), y1 + LATCH_FIT, z_top + LATCH_FIT)
    # Recess for the base lip.
    lid -= rounded_prism(ix0 - LIP_T - LIP_FIT, iy0 - LIP_T - LIP_FIT,
                         ix1 + LIP_T + LIP_FIT, iy1 + LIP_T + LIP_FIT,
                         SPLIT_Z - 1, SPLIT_Z + LIP_H + LIP_FIT,
                         max(CORNER_R - WALL + LIP_T, 0.5))

    # OLED window: active area + margin, flared outwards towards the top.
    wu0, wv0, wu1, wv1 = 7.70, 9.98, 35.34, 27.6
    (wx0, wy0), (wx1, wy1) = ui_xy(ui, wu0, wv0), ui_xy(ui, wu1, wv1)
    ww = abs(wx1 - wx0) + 2 * WINDOW_MARGIN
    wh = abs(wy1 - wy0) + 2 * WINDOW_MARGIN
    wc = Pos((wx0 + wx1) / 2, (wy0 + wy1) / 2, DECK_UNDER - 0.01)
    lid -= extrude(wc * Rectangle(ww, wh), amount=DECK_T + 0.02, taper=-WINDOW_FLARE)

    # Encoder: body passes through, knob sits above the deck.
    ex, ey = ui_xy(ui, 64.90 - 11.61, 17.60)
    lid -= Pos(ex, ey, DECK_UNDER - 1) * Box(ENCODER_HOLE, ENCODER_HOLE, DECK_T + 2,
                                             align=(Align.CENTER, Align.CENTER, Align.MIN))

    # Flexure buttons over BACK (towards +Y) and CONFIRM (towards -Y); each tab
    # hinges on the side away from the encoder.
    for v_btn, away in ((3.89 + 1.815, +1), (35.03 - 7.54 + 1.815, -1)):
        bx, by = ui_xy(ui, 64.90 - 14.66 + 3.05, v_btn)
        free = by - away * BTN_TAB_W / 2       # free end, towards the encoder
        hinge = free + away * BTN_TAB_L
        ty0, ty1 = sorted((free, hinge))
        # U-shaped slot: cut the outline, then put the tab back.
        sy0, sy1 = (ty0 - BTN_SLOT, ty1) if away > 0 else (ty0, ty1 + BTN_SLOT)
        lid -= box(bx - BTN_TAB_W / 2 - BTN_SLOT, sy0, DECK_UNDER - 1,
                   bx + BTN_TAB_W / 2 + BTN_SLOT, sy1, DECK_TOP + 1)
        lid += box(bx - BTN_TAB_W / 2, ty0, DECK_TOP - BTN_TAB_T, bx + BTN_TAB_W / 2, ty1, DECK_TOP)
        nub_bot = SWITCH_PLUNGER_TOP + BTN_PRESS_GAP
        lid += Pos(bx, by, nub_bot) * Cylinder(BTN_NUB_D / 2, DECK_TOP - BTN_TAB_T - nub_bot + 0.01,
                                                align=(Align.CENTER, Align.CENTER, Align.MIN))
        lid += Pos(bx, by, DECK_TOP - 0.01) * Cylinder(BTN_CAP_D / 2, BTN_CAP_H,
                                                        align=(Align.CENTER, Align.CENTER, Align.MIN))

    # Back wall: the nRF24 module ends pass through it. The base carries each
    # module on a support block; the lid wall is notched over the module and
    # its parts, and the base lip is relieved there.
    for rx, _ in radios:
        cx = rx + NRF_YC
        hw = NRF_W / 2 + NRF_NOTCH_FIT
        lid -= box(cx - hw, iy1 - LIP_T - 2, SPLIT_Z - 1, cx + hw, oy1 + 1,
                   NRF_PCB_TOP + NRF_PARTS_H)
        base -= box(cx - hw, iy1 - LIP_T - 2, SPLIT_Z, cx + hw, oy1 + 1, SPLIT_Z + LIP_H + 1)
        base += box(cx - NRF_W / 2, iy1 - NRF_SUPPORT_DEPTH, floor_top, cx + NRF_W / 2, oy1,
                    NRF_PCB_BOTTOM - NRF_SUPPORT_GAP)

    # Front wall: USB bay for both USB-C ports of the ESP32. The floor (base)
    # and the side walls (base up to the lip, lid above it) start inside the
    # front wall so they fuse with it, then the opening is cut through
    # everything out to beyond the connector faces. The strip deck is the roof.
    bay_z0 = USB_Z0 - USB_BAY_OPEN_MARGIN
    bay_floor_in = esp[1] - ESP_SOCKET_END - USB_BAY_FLOOR_GAP
    bay_side_in = esp[1] - ESP_PCB_END + USB_BAY_SIDE_PAST
    join_y = iy0 - 0.5
    bay_bot = bay_z0 - USB_BAY_FLOOR_T
    base += shelf(bay_x0, bay_x1, iy0, join_y, bay_floor_in, bay_z0, bay_bot)
    for sx0, sx1 in ((bay_x0 - USB_BAY_SIDE_W, bay_x0), (bay_x1, ix1 + 0.2)):
        base += shelf(sx0, sx1, iy0, join_y, bay_side_in, SPLIT_Z + LIP_H, bay_bot)
        lid += box(sx0, join_y, SPLIT_Z + LIP_H + LIP_FIT, sx1, bay_side_in, PLAT_UNDER + 0.01)
    base -= box(bay_x0, oy0 - 1, bay_z0, bay_x1, bay_side_in, SPLIT_Z + LIP_H + 1)
    lid -= box(bay_x0, oy0 - 1, SPLIT_Z - 1, bay_x1, bay_side_in, PLAT_UNDER)

    # Left wall: optional notch for JST power leads leaving the case (J2/J3).
    if CABLE_NOTCH:
        jy = (fp["J2"][1] + fp["J3"][1]) / 2
        cable = box(ox0 - 1, jy - CABLE_NOTCH_W / 2, SPLIT_Z - CABLE_NOTCH_H,
                    ix0 + LIP_T + 0.5, jy + CABLE_NOTCH_W / 2, SPLIT_Z + LIP_H + 1)
        base -= cable

    # Front wall: two USB-C power sockets, a plain rectangular hole each for
    # the snap-in body, plus an optional oval recess for the flange.
    for sx in USB_SOCK_X:
        base -= box(sx - USB_SOCK_HOLE_W / 2, oy0 - 1, USB_SOCK_Z - USB_SOCK_HOLE_H / 2,
                    sx + USB_SOCK_HOLE_W / 2, iy0 + 1, USB_SOCK_Z + USB_SOCK_HOLE_H / 2)
        if USB_SOCK_RECESS > 0:
            recess = Plane(origin=(sx, oy0 + USB_SOCK_RECESS, USB_SOCK_Z), x_dir=(1, 0, 0),
                           z_dir=(0, -1, 0)) * SlotOverall(USB_SOCK_FLANGE_W, USB_SOCK_FLANGE_H)
            base -= extrude(recess, amount=USB_SOCK_RECESS + 1)

    # Logo in relief on the deck, centred over the radio area.
    logo_box = None                                  # X0, Y0, X1, Y1 on the deck
    if LOGO_SVG.exists():
        logo = Compound(import_svg(str(LOGO_SVG)))
        lb = logo.bounding_box()
        k = min(LOGO_MAX_W / lb.size.X, LOGO_MAX_H / lb.size.Y)
        logo = logo.scale(k)
        lb = logo.bounding_box()
        lx = (ix0 + ix1) / 2
        ly = (fp["J1"][1] + 1.93 + iy1) / 2          # between UI module top edge and back wall
        logo = Pos(lx - lb.center().X, ly - lb.center().Y, DECK_TOP - 0.01) * logo
        lid += extrude(logo, amount=LOGO_RELIEF + 0.01)
        logo_box = (lx - lb.size.X / 2, ly - lb.size.Y / 2, lx + lb.size.X / 2, ly + lb.size.Y / 2)

    if VENT:
        m = VENT_MARGIN
        # Radio area: from the module sockets (board top edge, Y = 0) to the
        # back wall, where the module PCBs and their PA stages sit.
        ry0 = radios[0][1] + m
        ry1 = iy1 - m
        # Exhaust: lid deck over the radio area, around the logo.
        z0, z1 = DECK_UNDER - 1, DECK_TOP + 1
        if logo_box:
            gx0, gy0, gx1, gy1 = logo_box
            fields = [(ix0 + m, max(ry0, gy0 - m), gx0 - m, ry1, "y"),      # left of logo
                      (gx1 + m, max(ry0, gy0 - m), ix1 - m, ry1, "y"),      # right of logo
                      (ix0 + m, gy1 + m, ix1 - m, ry1, "x")]                # between logo and back wall
        else:
            fields = [(ix0 + m, ry0, ix1 - m, ry1, "x")]
        for fx0, fy0, fx1, fy1, along in fields:
            if fx1 - fx0 > VENT_W and fy1 - fy0 > VENT_W:
                for c in vent_slots(fx0, fy0, z0, fx1, fy1, z1, along):
                    lid -= c
        # Intake: base floor under the module area, clear of the module
        # support blocks at the back wall.
        for c in vent_slots(ix0 + m, ry0, floor_bot - 1, ix1 - m,
                            iy1 - NRF_SUPPORT_DEPTH - m, floor_top + 1, "x"):
            base -= c
        # Intake: side walls near the back, vertical slots below the lip.
        wz0, wz1 = floor_top + 1.5, SPLIT_Z - 2.0
        for wx0, wx1 in ((ox0 - 1, ix0 + 1), (ix1 - 1, ox1 + 1)):
            for ya, yb in tile(ry0, iy1 - CORNER_R - m, VENT_W, VENT_RIB):
                base -= box(wx0, ya, wz0, wx1, yb, wz1)

    # Version engraved in the floor underside, centred, mirrored so it reads
    # correctly with the case turned over.
    if ENGRAVE_TEXT:
        txt = Text(ENGRAVE_TEXT, ENGRAVE_SIZE, align=(Align.CENTER, Align.CENTER))
        txt = txt.mirror(Plane.XZ)
        txt = Pos((ox0 + ox1) / 2, (oy0 + oy1) / 2, floor_bot - 0.01) * txt
        base -= extrude(txt, amount=ENGRAVE_DEPTH + 0.01)

    return base, lid


def usb_socket_model():
    """The 2-wire USB-C panel socket: oval flange with the USB-C opening in
    its face, rectangular snap-in body behind it. Flange face at Y = 0 facing
    -Y, body along +Y, centred on X and Z."""
    face = Plane(origin=(0, 0, 0), x_dir=(1, 0, 0), z_dir=(0, -1, 0))
    flange = extrude(face * SlotOverall(USB_SOCK_FLANGE_W, USB_SOCK_FLANGE_H), amount=USB_SOCK_FLANGE_T)
    body = box(-USB_SOCK_HOLE_W / 2, 0, -USB_SOCK_HOLE_H / 2,
               USB_SOCK_HOLE_W / 2, USB_SOCK_DEPTH, USB_SOCK_HOLE_H / 2)
    port = extrude(face * SlotOverall(USB_PORT_W, USB_PORT_H), amount=USB_SOCK_FLANGE_T + 6.0)
    return (flange + body) - port


def usb_sockets():
    """Both sockets in place on the front wall, for the viewer and the
    clearance check."""
    iy0 = -73.2 - CLEARANCE
    oy0 = iy0 - WALL
    model = usb_socket_model()
    return Compound([Pos(sx, oy0 + USB_SOCK_RECESS, USB_SOCK_Z) * model for sx in USB_SOCK_X])


def check_clearance(pcb, base, lid, sockets=None):
    """Report any overlap between the case and the PCB assembly. Untrimmed
    THT leads in the models are ignored below -LEAD_TRIM. The USB socket
    bodies are checked against the PCB parts as well."""
    problems = []
    bb = pcb.bounding_box()
    keep = box(bb.min.X - 1, bb.min.Y - 1, -LEAD_TRIM, bb.max.X + 1, bb.max.Y + 1, bb.max.Z + 1)
    others = [("base", base), ("lid", lid)]
    if sockets is not None:
        others.append(("usb sockets", sockets))
    for top in pcb.children:
        for child in parts_of(top):
            clipped = child & keep
            if not clipped.solids():          # entirely outside the clip box
                continue
            for name, part in others:
                v = (part & clipped).volume
                if v > 0.01:
                    label = child.label if child is top else f"{top.label}/{child.label}"
                    problems.append(f"  {name} intersects {label}: {v:.2f} mm^3")
    print("clearance check:", "OK" if not problems else "")
    for p in problems:
        print(p)


def export(base, lid):
    OUT.mkdir(exist_ok=True)
    export_step(usb_socket_model(), str(OUT / "usb_socket_2pin.step"))
    for name, part in (("enclosure_base", base), ("enclosure_lid", lid)):
        export_step(part, str(OUT / f"{name}.step"))
        export_stl(part, str(OUT / f"{name}.stl"))
        mesher = Mesher()
        mesher.add_shape(part)
        mesher.write(str(OUT / f"{name}.3mf"))


